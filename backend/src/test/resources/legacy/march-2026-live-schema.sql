-- The live database as the March 2026 app left it (commit 6abc999, Hibernate ddl-auto=update, no Flyway).
-- Schema: pg_dump --schema-only of a database that 6abc999 created on PostgreSQL 16 (only the two tables,
-- enums stored as STRING with Hibernate CHECK constraints, a random unique constraint name).
-- Data: written through the March API (check-in, check-out, pay, runaway), then dated back to March.
-- Plates are stored as typed (upper-case, spaces and '-' kept); RUNAWAY fee is the unpaid debt.

CREATE TABLE public.active_park_spots (
    id bigint NOT NULL,
    current_plate character varying(255) NOT NULL,
    current_type character varying(255),
    entry_time timestamp(6) without time zone,
    neighborhood character varying(255),
    region character varying(255),
    side character varying(255),
    status character varying(255),
    street character varying(255) NOT NULL,
    CONSTRAINT active_park_spots_current_type_check CHECK (((current_type)::text = ANY ((ARRAY['SMALL'::character varying, 'LARGE'::character varying])::text[]))),
    CONSTRAINT active_park_spots_status_check CHECK (((status)::text = ANY ((ARRAY['ACTIVE'::character varying, 'PAID'::character varying, 'RUNAWAY'::character varying])::text[]))),
    CONSTRAINT active_park_spots_street_check CHECK (((street)::text = ANY ((ARRAY['TEVFIK_BEY'::character varying, 'ALI_RIZA_OZKAY'::character varying, 'CUMHURIYET'::character varying])::text[])))
);

ALTER TABLE public.active_park_spots ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.active_park_spots_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE public.parking_records (
    id bigint NOT NULL,
    entry_time timestamp(6) without time zone,
    exit_time timestamp(6) without time zone,
    fee double precision,
    license_plate character varying(255),
    neighborhood character varying(255),
    region character varying(255),
    status character varying(255),
    street character varying(255),
    vehicle_type character varying(255),
    CONSTRAINT parking_records_status_check CHECK (((status)::text = ANY ((ARRAY['ACTIVE'::character varying, 'PAID'::character varying, 'RUNAWAY'::character varying])::text[]))),
    CONSTRAINT parking_records_street_check CHECK (((street)::text = ANY ((ARRAY['TEVFIK_BEY'::character varying, 'ALI_RIZA_OZKAY'::character varying, 'CUMHURIYET'::character varying])::text[]))),
    CONSTRAINT parking_records_vehicle_type_check CHECK (((vehicle_type)::text = ANY ((ARRAY['SMALL'::character varying, 'LARGE'::character varying])::text[])))
);

ALTER TABLE public.parking_records ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.parking_records_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

