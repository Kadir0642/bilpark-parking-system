-- V1: pre-stage-2 schema, exactly as Hibernate ddl-auto=update created it (commit 964ce7e).
-- On the live database this script is NOT run (Flyway baselines at version 1); it only runs on empty databases.

CREATE TABLE IF NOT EXISTS zones (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    street         varchar(255) NOT NULL,
    zone_number    integer      NOT NULL,
    zone_name      varchar(255) NOT NULL,
    left_landmark  varchar(255),
    right_landmark varchar(255),
    CONSTRAINT uk_zones_street_zone_number UNIQUE (street, zone_number)
);

CREATE TABLE IF NOT EXISTS users (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        varchar(255) NOT NULL,
    password        varchar(255) NOT NULL,
    role            varchar(255) NOT NULL,
    zone_id         bigint,
    last_login_time timestamp(6),
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT fk_users_zone FOREIGN KEY (zone_id) REFERENCES zones (id)
);

CREATE TABLE IF NOT EXISTS active_park_spots (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version       bigint,
    current_plate varchar(255) NOT NULL,
    street        varchar(255) NOT NULL,
    zone_id       bigint,
    region        varchar(255),
    neighborhood  varchar(255),
    side          varchar(255),
    entry_time    timestamp(6),
    current_type  varchar(255),
    status        varchar(255),
    CONSTRAINT uk_active_park_spots_current_plate UNIQUE (current_plate),
    CONSTRAINT fk_active_park_spots_zone FOREIGN KEY (zone_id) REFERENCES zones (id)
);

CREATE TABLE IF NOT EXISTS parking_records (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    license_plate varchar(255),
    street        varchar(255),
    zone_id       bigint,
    region        varchar(255),
    neighborhood  varchar(255),
    entry_time    timestamp(6),
    exit_time     timestamp(6),
    vehicle_type  varchar(255),
    fee           float(53),
    status        varchar(255),
    debt_paid     boolean NOT NULL,
    CONSTRAINT fk_parking_records_zone FOREIGN KEY (zone_id) REFERENCES zones (id)
);

CREATE TABLE IF NOT EXISTS subscriptions (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    license_plate varchar(255) NOT NULL,
    vehicle_type  varchar(255) NOT NULL,
    start_date    date NOT NULL,
    end_date      date NOT NULL,
    monthly_fee   float(53),
    status        varchar(255) NOT NULL,
    owner_name    varchar(255),
    owner_phone   varchar(255),
    CONSTRAINT uk_subscriptions_license_plate UNIQUE (license_plate)
);

CREATE TABLE IF NOT EXISTS fiscal_years (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    start_date date NOT NULL,
    end_date   date NOT NULL,
    label      varchar(255) NOT NULL,
    is_active  boolean NOT NULL
);
