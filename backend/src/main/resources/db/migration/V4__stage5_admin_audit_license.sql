-- 5) Key/value settings (performance weights, annual rent per year, retention bookkeeping)
CREATE TABLE IF NOT EXISTS app_settings (
    setting_key   varchar(100) PRIMARY KEY,
    setting_value text         NOT NULL,
    updated_at    timestamp(6) NOT NULL,
    updated_by    varchar(255) NOT NULL
);

-- 6) Unexpected server errors for the developer's "recent errors" view
CREATE TABLE IF NOT EXISTS error_logs (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      timestamp(6) NOT NULL,
    method          varchar(10),
    path            varchar(255),
    error_code      varchar(50),
    exception_class varchar(255),
    message         varchar(1000),
    stack_excerpt   text,
    username        varchar(255)
);
CREATE INDEX IF NOT EXISTS ix_error_logs_created_at ON error_logs (created_at);
