-- 3) Audit log. Actor is a snapshot (no FK) so the row survives user changes.
CREATE TABLE IF NOT EXISTS audit_logs (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at     timestamp(6) NOT NULL,
    actor_id       bigint,
    actor_username varchar(255) NOT NULL,
    actor_role     varchar(20),
    device_id      varchar(64),
    ip_address     varchar(64),
    action         varchar(50)  NOT NULL,
    entity_type    varchar(50),
    entity_id      varchar(100),
    summary        varchar(500),
    before_data    text,
    after_data     text
);
CREATE INDEX IF NOT EXISTS ix_audit_logs_created_at ON audit_logs (created_at);
CREATE INDEX IF NOT EXISTS ix_audit_logs_action ON audit_logs (action);
CREATE INDEX IF NOT EXISTS ix_audit_logs_actor ON audit_logs (actor_username);

-- 4) License: a single visible row (id = 1). Expiry starts one year from the first deploy;
--    the developer sets the contract dates. Grace days come from the contract.
CREATE TABLE IF NOT EXISTS license_info (
    id          bigint       PRIMARY KEY,
    licensee    varchar(255) NOT NULL,
    expires_on  date         NOT NULL,
    grace_days  integer      NOT NULL,
    note        varchar(500),
    updated_at  timestamp(6) NOT NULL,
    updated_by  varchar(255) NOT NULL
);
