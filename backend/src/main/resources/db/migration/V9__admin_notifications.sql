-- V9: admin notification inbox (docs/api-bildirimler.md, section 2).
-- admin_notifications: system events the admin should know about (update, password reset, license, announcements).
-- admin_notification_reads: who read which notification (one row per notification and user).
CREATE TABLE IF NOT EXISTS admin_notifications (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type        varchar(40)   NOT NULL,
    title       varchar(120)  NOT NULL,
    body        varchar(2000),
    created_at  timestamp(6)  NOT NULL,
    created_by  varchar(100)  NOT NULL,
    valid_until timestamp(6)
);
CREATE INDEX IF NOT EXISTS ix_admin_notifications_created_at ON admin_notifications (created_at);

CREATE TABLE IF NOT EXISTS admin_notification_reads (
    notification_id bigint        NOT NULL REFERENCES admin_notifications (id) ON DELETE CASCADE,
    user_id         bigint        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    read_at         timestamp(6)  NOT NULL,
    PRIMARY KEY (notification_id, user_id)
);
