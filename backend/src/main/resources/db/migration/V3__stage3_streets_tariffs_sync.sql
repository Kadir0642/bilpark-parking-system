-- 2) Versioned tariffs. Lifecycle: DRAFT -> SCHEDULED -> ACTIVE -> ARCHIVED (cancel: DRAFT/SCHEDULED -> ARCHIVED).
--    paid_end = 00:00 means midnight (end of day).
CREATE TABLE IF NOT EXISTS tariffs (
    id                         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status                     varchar(20)  NOT NULL,
    small_first_hour           float(53)    NOT NULL,
    small_extra_hour           float(53)    NOT NULL,
    large_first_hour           float(53)    NOT NULL,
    large_extra_hour           float(53)    NOT NULL,
    free_minutes               integer      NOT NULL,
    paid_start                 time         NOT NULL,
    paid_end                   time         NOT NULL,
    subscription_small_monthly float(53)    NOT NULL,
    subscription_large_monthly float(53)    NOT NULL,
    effective_from             timestamp(6),
    activated_at               timestamp(6),
    archived_at                timestamp(6),
    note                       varchar(500),
    created_by_id              bigint,
    created_by_username        varchar(255) NOT NULL,
    created_at                 timestamp(6) NOT NULL,
    CONSTRAINT fk_tariffs_created_by FOREIGN KEY (created_by_id) REFERENCES users (id),
    CONSTRAINT ck_tariffs_status CHECK (status IN ('DRAFT', 'SCHEDULED', 'ACTIVE', 'ARCHIVED'))
);

-- At most one ACTIVE and one SCHEDULED tariff at any time
CREATE UNIQUE INDEX IF NOT EXISTS ux_tariffs_one_active ON tariffs (status) WHERE status = 'ACTIVE';
CREATE UNIQUE INDEX IF NOT EXISTS ux_tariffs_one_scheduled ON tariffs (status) WHERE status = 'SCHEDULED';

