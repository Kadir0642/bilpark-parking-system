-- 3) parking_records: which tariff version priced the record and how many minutes were billable.
--    Historical rows keep NULL (priced by the old hard-coded rules).
ALTER TABLE parking_records ADD COLUMN IF NOT EXISTS tariff_id bigint;
ALTER TABLE parking_records ADD COLUMN IF NOT EXISTS paid_minutes integer;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint c
        JOIN pg_class t ON t.oid = c.conrelid
        JOIN pg_namespace n ON n.oid = t.relnamespace
        WHERE n.nspname = current_schema() AND t.relname = 'parking_records'
          AND c.conname = 'fk_parking_records_tariff') THEN
        ALTER TABLE parking_records
            ADD CONSTRAINT fk_parking_records_tariff FOREIGN KEY (tariff_id) REFERENCES tariffs (id);
    END IF;
END $$;

-- 4) users: deactivation (a passive user can neither log in nor use an existing token)
ALTER TABLE users ADD COLUMN IF NOT EXISTS active boolean NOT NULL DEFAULT true;

-- 5) Live sync change log. id is the sync version clients pass as ?since=.
--    scope: ZONE (zone_id/street), GLOBAL (everyone), USER (target_user_id only; admins see all).
CREATE TABLE IF NOT EXISTS sync_events (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type           varchar(40)  NOT NULL,
    scope          varchar(10)  NOT NULL,
    zone_id        bigint,
    street         varchar(50),
    target_user_id bigint,
    payload        text,
    created_at     timestamp(6) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_sync_events_created_at ON sync_events (created_at);
